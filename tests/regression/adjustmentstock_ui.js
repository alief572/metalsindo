'use strict';
const assert = require('assert');
const app = require('../../assets/js/adjustmentstock.js');
assert.strictEqual(app.formatAmount(1000, 2), '1.000,00');
assert.strictEqual(app.formatAmount(0, 0), '0');
assert.strictEqual(app.formatAmount(null, 2), '—');
const state = app.state();
assert.strictEqual(app.weightForQty(state, 2, 100, ''), 200);
state.dirty = true;
assert.strictEqual(app.weightForQty(state, 3, 100, '25'), '25', 'manual weight must survive qty edits');
assert.strictEqual(app.weightForQty(state, 0, 100, '0'), '0', 'explicit zero must survive');
assert.strictEqual(app.state().dirty, false, 'new selection resets dirty state');
assert.deepStrictEqual(app.layout('PLUS', 'new'), { plus: true, source: false, newLot: true, transfer: false });
assert.deepStrictEqual(app.layout('MINUS', 'new'), { plus: false, source: true, newLot: false, transfer: false });
assert.deepStrictEqual(app.layout('MUTASI', 'existing'), { plus: false, source: true, newLot: false, transfer: true });
const lot = { qty: 10, weight: 100, totalweight: 1000, sisa_spk: 90 };
assert.deepStrictEqual(app.preview(lot, 0, 25, -1), { qty: 10, gross: 975, operational: 875, invalid: false });
assert.strictEqual(app.preview(lot, 2, 100, -1).qty, 8);
assert.strictEqual(app.preview(lot, 10, 10, -1).invalid, true);
assert.strictEqual(app.preview(lot, 7, 0, -1).invalid, true);
assert.strictEqual(app.preview(Object.assign({}, lot, { sisa_spk: null }), 0, 25, -1).invalid, true);
assert.strictEqual(app.compatible({ lotno: 'A', customer: 'C' }, { lotno: 'A', customer: 'X' }), false);
assert.strictEqual(app.compatible({ lotno: 'A', customer: null }, { lotno: 'A', customer: '' }), true);
assert.strictEqual(app.unavailable(Object.assign({}, lot, { aktif: 'Y' })), '');
assert(app.unavailable(Object.assign({}, lot, { aktif: 'Y', qty: 0 })).includes('Qty nol'));
assert.strictEqual(app.unavailable(Object.assign({}, lot, { aktif: 'N' })), 'Nonaktif');
assert(app.unavailable(Object.assign({}, lot, { aktif: null })).includes('Status aktif'));
console.log('PASS adjustment UI: independent weight, manual/zero values, mode switching, preview and target compatibility');
